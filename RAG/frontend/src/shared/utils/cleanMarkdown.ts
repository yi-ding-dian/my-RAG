/**
 * LLM 回答正文的 Markdown 结构符号清洗。
 *
 * 背景：回答气泡是纯文本渲染（只支持 [n] 引用标与 ![]() 图片），模型偶尔会
 * 输出 Markdown 结构符号（如 "### 4.3 开源大模型的兴起"），导致裸符号展示。
 * 此处保守清洗"行首的 Markdown 结构符号"，让回答以干净纯文本呈现。
 *
 * 规则（只处理"行首 + 符号 + 空白"形态，防误伤正文）：
 * - `### `（1~6 级标题）
 * - `- ` / `* ` / `+ `（无序列表）
 * - `1. ` / `1、`（有序列表）
 * - `> `（引用）
 * - 行首最多允许 3 个空格/制表（Markdown 允许的缩进）
 *
 * 不处理：`**加粗**` 等行内符号（误伤风险高，且少见）；文档原文/引用文本
 * （它们本就可能是 Markdown 源文，清洗会破坏内容）。
 */
export const cleanAnswerText = (text: string): string =>
  text.replace(
    /^[ \t]{0,3}(#{1,6}[ \t]+|[-*+][ \t]+|\d+[.、][ \t]+|>[ \t]+)/gm,
    '',
  );
