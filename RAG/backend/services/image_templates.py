# 没选模板时用的那套（也是「通用」的兜底语义）
DEFAULT_TEMPLATE_NAME = "通用"


def template_options(configured: Optional[List[dict]] = None) -> List[Dict[str, str]]:
    """可选的模板列表：超管配的非空则整体替代内置

    返回值只含 name/prompt（给前端下拉与解析共用），顺序即展示顺序。
    """
    items = [m for m in (configured or []) if isinstance(m, dict)]
    usable = [{"name": str(m.get("name") or "").strip(),
               "prompt": str(m.get("prompt") or "")}
              for m in items]
    usable = [m for m in usable if m["name"] and m["prompt"]]
    return usable or [dict(t) for t in BUILTIN_IMAGE_TEMPLATES]


def resolve_template_body(name: str = "",
                          configured: Optional[List[dict]] = None) -> str:
    """按名取模板**正文**；名字为空或找不到 → 内置默认那套

    找不到时回退而不是返回空串：模板是读图的骨架，缺了它两个调用方都只能
    用各自硬编码的老提示词——那等于"部门选了个失效的名字，行为悄悄变了"。
    """
    options = template_options(configured)
    want = (name or "").strip()
    if want:
        hit = next((t for t in options if t["name"] == want), None)
        if hit is not None:
            return hit["prompt"]
    fallback = next((t for t in options if t["name"] == DEFAULT_TEMPLATE_NAME),
                    None)
    return (fallback or options[0])["prompt"]
