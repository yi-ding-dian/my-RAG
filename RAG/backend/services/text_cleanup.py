"""解析文本清洗（解析产物落盘前的通用文本规范化）

当前仅一项：剥离 MinerU 误识别的 <sub>/<sup> 上下标标签。

背景：PDF 里没有"上标/下标"语义，只有字符坐标与字号；MinerU 按"字号更小 +
基线偏移"推断上下标，但文档标题/引号等使用了不同字体（标题字体、全角引号），
坐标与正文对不齐时大量误判，典型形态：
- 标题编号判成下标（如 3.1 → <sub>3.1</sub>）
- 标题文字判成上标（如整个小节标题）
- 中文引号判成下标

这些标签会进入切块文本/向量/LLM 上下文，属噪声。清洗策略：**去标签、
保留内部文字**（`## <sub>3.1</sub> 工程创建` → `## 3.1 工程创建`）——
文字内容完整可检索，仅在"真上下标"（化学式 H₂O、幂 10³）场景损失排版视觉
（RAG 场景可忽略，且此类真判在本项目文档中极罕见）。

清洗时机：**解析产物落盘前**（_stage_parse 中 html_tables_to_pipe 之后）。
原因：切块系统有严格偏移契约（块文本 == 全文[起始:结束]），若在切块阶段
清洗会导致偏移错位；落盘前清洗则全文/切块/偏移三者一致。
"""
from __future__ import annotations

import re

# <sub>/<sup> 开闭标签（含带属性形式 <sub style="...">；大小写不敏感）
_SUBSUP_TAG_RE = re.compile(r"</?(?:sub|sup)\b[^>]*>", re.IGNORECASE)


def strip_subsup_tags(text: str) -> str:
    """剥离 <sub>/<sup> 标签，保留内部文字（解析产物上下标误判清洗）

    - `## <sub>3.1</sub> 工程创建` → `## 3.1 工程创建`
    - `实时命令<sub>”</sub>界面` → `实时命令”界面`
    - 无标签文本原样返回（零开销）
    """
    if not text or "<" not in text:
        return text
    return _SUBSUP_TAG_RE.sub("", text)
